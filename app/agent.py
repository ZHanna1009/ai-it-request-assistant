
import os
from langchain.tools import tool
from langchain.agents import create_agent

SYSTEMS = ["SAP", "Power BI", "АСКиУТСиР"]

CATEGORIES = [
    "Доступ к системам",
    "Ошибки системы",
    "Консультация",
    "Создание новых отчетов",
    "Автоматизация новых процессов",
    "Обучение пользователей",
]


@tool
def check_system(system: str) -> str:
    """Проверяет, относится ли система к области проекта."""
    if system in SYSTEMS:
        return f"Система '{system}' входит в область проекта."
    return f"Система '{system}' не входит в область проекта."


@tool
def check_category(category: str) -> str:
    """Проверяет категорию IT-заявки."""
    if category in CATEGORIES:
        return f"Категория '{category}' допустима."
    return f"Категория '{category}' не входит в справочник проекта."


@tool
def get_required_information(category: str) -> str:
    """Возвращает обязательные сведения для первичного анализа заявки."""
    requirements = {
        "Доступ к системам":
            "логин или идентификатор пользователя, система, точный текст ошибки",
        "Ошибки системы":
            "система, название операции или раздела, точный текст ошибки, шаги воспроизведения",
        "Консультация":
            "что пользователь хочет получить или выполнить, система и используемый раздел",
        "Создание новых отчетов":
            "цель отчета, показатели, источник данных, пользователи отчета",
        "Автоматизация новых процессов":
            "описание процесса, текущие шаги, системы и ожидаемый результат",
        "Обучение пользователей":
            "система, тема обучения, уровень подготовки пользователей и требуемый результат",
    }

    return requirements.get(
        category,
        "Недостаточно данных для определения обязательной информации."
    )


@tool
def check_scope(question: str) -> str:
    """Проверяет, относится ли запрос к области IT-поддержки проекта."""
    keywords = [
        "sap", "power bi", "аскиутсир",
        "доступ", "ошибка", "отчет", "отчёт",
        "автоматиза", "обучен", "система",
        "it", "айти"
    ]

    q = question.lower()

    if any(word in q for word in keywords):
        return "Запрос потенциально относится к области проекта."

    return "Запрос не содержит признаков обращения по поддерживаемым IT-системам. Требуется отказ."


TOOLS = [
    check_system,
    check_category,
    get_required_information,
    check_scope,
]


AGENT_SYSTEM_PROMPT = """
Ты AI IT Request Assistant.

Твоя задача: первично классифицировать IT-заявку по справочнику проекта.

Поддерживаемые системы:
SAP
Power BI
АСКиУТСиР

Поддерживаемые категории:
Доступ к системам
Ошибки системы
Консультация
Создание новых отчетов
Автоматизация новых процессов
Обучение пользователей

ВАЖНЫЕ ПРАВИЛА:
- Используй только категории из этого списка.
- Никогда не создавай новые категории.
- Не придумывай факты о конкретной системе.
- Не предлагай конкретные действия или операции, если их нет в заявке или результатах инструментов.
- Используй инструменты для проверки системы, категории, обязательной информации и области запроса.
- Если информации недостаточно, укажи недостающую информацию.
- Если запрос вне области проекта, используй must_refuse=true.
- Финальное решение принимает IT специалист.

Верни только JSON со следующими полями:
{
  "system": "...",
  "category": "...",
  "missing_information": "...",
  "expected_action": "...",
  "must_refuse": false
}
"""


def create_project_agent():
    from langchain_openai import ChatOpenAI

    model_name = os.getenv("MODEL", "gpt-5-mini")

    model = ChatOpenAI(
        model=model_name
    )

    return create_agent(
        model=model,
        tools=TOOLS,
        system_prompt=AGENT_SYSTEM_PROMPT,
    )
